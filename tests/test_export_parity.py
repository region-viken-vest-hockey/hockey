def test_comparator_reports_missing_extra_and_duplicate_ids():
    from tournament_scheduler.pipeline.export_parity.comparator import compare_projections
    from tournament_scheduler.pipeline.export_parity.records import ArtifactProjection, TournamentRecord

    primary = ArtifactProjection(
        kind="xlsx",
        path="a.xlsx",
        exists=True,
        records=[
            TournamentRecord(tournament_id="rvv-1"),
            TournamentRecord(tournament_id="rvv-1"),
            TournamentRecord(tournament_id="rvv-2"),
        ],
    )
    secondary = ArtifactProjection(
        kind="html",
        path="a.html",
        exists=True,
        records=[TournamentRecord(tournament_id="rvv-1"), TournamentRecord(tournament_id="rvv-3")],
    )

    comparison = compare_projections(primary, secondary)

    assert comparison["duplicate_ids"]["xlsx"] == ["rvv-1"]
    assert comparison["extra_ids"] == ["rvv-3"]
    assert comparison["missing_ids"] == ["rvv-2"]


def test_three_cancelled_rows_compare_despite_different_presentation(tmp_path):
    teams = [Team(club=f"Club{i}", label=f"U10-{i}", age_group="U10") for i in range(4)]
    tournaments = [
        Tournament(
            id=f"rvv-000{i}",
            date=date(2026, 10, 10 + i),
            arena="Jar Isforum",
            age_group="U10",
            teams=teams,
            games=_games(teams),
            host_club="Jar",
            start_time="09:00",
            cancelled=True,
            cancellation_reason=f"Årsak {i}",
        )
        for i in range(3)
    ]
    plan = SeasonPlan(tournaments=tournaments, start_date=date(2026, 10, 1), end_date=date(2027, 4, 30))
    export_dir = tmp_path / "export"
    export_dir.mkdir()
    ice = {"U10": 150}
    SeasonPlanExporter().export(plan, str(export_dir / "season_plan.xlsx"), ice_time_for_age_group=ice)
