"""Hermetic tests for XLSX/HTML artifact parity and canonical freshness.

The tests exercise the *real* exporters and read the generated bytes back, so a
shared in-memory projection cannot mask a rendering/parsing mismatch.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import openpyxl

from tournament_scheduler.excel.plan_exporter import SeasonPlanExporter
from tournament_scheduler.html.html_exporter import HtmlExporter
from tournament_scheduler.models import SeasonPlan, Team, Tournament
from tournament_scheduler.pipeline.export_parity import (
    STATUS_FAIL,
    STATUS_NOT_CHECKABLE,
    STATUS_PASS,
    verify_export_parity,
)
from tournament_scheduler.pipeline.export_parity.gate import publish_parity_gate
from tournament_scheduler.season_planner import SeasonPlanner

REVISION = "rev-abc123"
OTHER_REVISION = "rev-def456"


def _games(teams):
    return SeasonPlanner.generate_round_robin_games(teams, parallel_games=2)


def _fixture() -> SeasonPlan:
    teams_u10 = [Team(club=f"Club{i}", label=f"U10-{i}", age_group="U10") for i in range(4)]
    # Two legitimate same-day/same-host/same-age events (duplicate Holmen U12).
    dup_a = [Team(club="Holmen", label=f"Holmen A{i}", age_group="U12") for i in range(4)]
    dup_b = [Team(club="Holmen", label=f"Holmen B{i}", age_group="U12") for i in range(4)]
    tournaments = [
        Tournament(
            id="rvv-0001",
            date=date(2026, 10, 10),
            arena="Jar Isforum",
            age_group="U10",
            teams=teams_u10,
            games=_games(teams_u10),
            host_club="Jar",
            start_time="09:00",
        ),
        Tournament(
            id="rvv-0002",
            date=date(2026, 11, 7),
            arena="Holmen ishall",
            age_group="U12",
            teams=dup_a,
            games=_games(dup_a),
            host_club="Holmen",
            start_time="10:00",
        ),
        Tournament(
            id="rvv-0003",
            date=date(2026, 11, 7),
            arena="Holmen ishall",
            age_group="U12",
            teams=dup_b,
            games=_games(dup_b),
            host_club="Holmen",
            start_time="10:00",
        ),
        Tournament(
            id="rvv-0004",
            date=date(2026, 12, 5),
            arena="Jar Isforum",
            age_group="U10",
            teams=teams_u10,
            games=_games(teams_u10),
            host_club="Jar",
            start_time="09:00",
            cancelled=True,
            cancellation_reason="Regionalt sperret helg",
        ),
    ]
    # Reverse the XLSX row order relative to the HTML chronological order.
    return SeasonPlan(tournaments=list(reversed(tournaments)), start_date=date(2026, 10, 1), end_date=date(2027, 4, 30))


def _approval_status() -> dict:
    return {
        "tournaments": [
            {"tournament_id": "rvv-0001", "status": "approved", "placement_locked": True, "participants_locked": False},
            {"tournament_id": "rvv-0002", "status": "pending_review", "placement_locked": False, "participants_locked": False},
        ]
    }


def _booking_status() -> dict:
    return {
        "tournaments": [
            {"tournament_id": "rvv-0001", "status": "confirmed_booked", "needs_attention": False},
            {"tournament_id": "rvv-0002", "status": "confirmed_not_booked", "needs_attention": True},
        ]
    }


def _export_pair(tmp_path: Path, revision: str = REVISION) -> tuple[Path, Path, Path]:
    export_dir = tmp_path / "export"
    export_dir.mkdir()
    plan = _fixture()
    ice = {"U10": 150, "U12": 120}
    approval = _approval_status()
    booking = _booking_status()
    xlsx = export_dir / "season_plan.xlsx"
    html = export_dir / "season_plan.html"
    SeasonPlanExporter().export(
        plan,
        str(xlsx),
        ice_time_for_age_group=ice,
        decision_status={"approval": approval, "booking": booking},
        season_metadata={"season": "2026-2027", "canonical_revision": revision},
    )
    HtmlExporter().export(
        plan,
        str(html),
        pipeline_meta={
            "canonical_revision": revision,
            "approval_status": approval,
            "booking_status": booking,
        },
        ice_time_for_age_group=ice,
    )
    return export_dir, xlsx, html


def test_real_exports_are_artifact_parity_clean(tmp_path):
    export_dir, _, _ = _export_pair(tmp_path)

    report = verify_export_parity(export_dir)

    assert report["status"] == STATUS_PASS, report["reasons"]
    assert report["primary"]["tournament_count"] == 4
    assert report["secondary"]["tournament_count"] == 4
    assert report["canonical_revision"] == REVISION


def test_two_same_day_events_compare_by_stable_id_not_row_order(tmp_path):
    export_dir, _, _ = _export_pair(tmp_path)
    report = verify_export_parity(export_dir)
    assert report["status"] == STATUS_PASS
    # Both duplicate Holmen U12 events survive as distinct ids.
    assert not report["comparison"]["duplicate_ids"]["xlsx"]
    assert not report["comparison"]["duplicate_ids"]["html"]


def test_edited_excel_booking_cell_fails_with_id_and_field(tmp_path):
    export_dir, xlsx, _ = _export_pair(tmp_path)
    workbook = openpyxl.load_workbook(xlsx)
    sheet = workbook["Sesongoversikt"]
    header = [cell.value for cell in sheet[1]]
    status_col = header.index("Bookingsstatus") + 1
    id_col = header.index("Turnerings-ID") + 1
    target_row = next(
        row for row in range(2, sheet.max_row + 1) if sheet.cell(row=row, column=id_col).value == "rvv-0001"
    )
    sheet.cell(row=target_row, column=status_col).value = "confirmed_not_booked"
    workbook.save(xlsx)

    report = verify_export_parity(export_dir)

    assert report["status"] == STATUS_FAIL
    mismatches = report["comparison"]["mismatches"]
    assert any(m["tournament_id"] == "rvv-0001" and m["field"] == "booking_status" for m in mismatches)


def test_edited_html_booking_flag_fails(tmp_path):
    export_dir, _, html = _export_pair(tmp_path)
    text = html.read_text(encoding="utf-8")
    text = text.replace('"bs": "confirmed_not_booked"', '"bs": "confirmed_booked"', 1)
    html.write_text(text, encoding="utf-8")

    report = verify_export_parity(export_dir)

    assert report["status"] == STATUS_FAIL
    assert any(m["field"] == "booking_status" for m in report["comparison"]["mismatches"])


def test_one_sided_cancellation_fails(tmp_path):
    export_dir, xlsx, _ = _export_pair(tmp_path)
    workbook = openpyxl.load_workbook(xlsx)
    sheet = workbook["Sesongoversikt"]
    header = [cell.value for cell in sheet[1]]
    date_col = header.index("Dato") + 1
    id_col = header.index("Turnerings-ID") + 1
    reason_col = header.index("Avlysningsårsak") + 1
    cancelled_col = header.index("Avlyst") + 1
    target_row = next(
        row for row in range(2, sheet.max_row + 1) if sheet.cell(row=row, column=id_col).value == "rvv-0004"
    )
    sheet.cell(row=target_row, column=date_col).value = "05.12.2026"
    sheet.cell(row=target_row, column=reason_col).value = ""
    sheet.cell(row=target_row, column=cancelled_col).value = ""
    workbook.save(xlsx)

    report = verify_export_parity(export_dir)

    assert report["status"] == STATUS_FAIL
    assert any(m["tournament_id"] == "rvv-0004" and m["field"] == "cancelled" for m in report["comparison"]["mismatches"])


