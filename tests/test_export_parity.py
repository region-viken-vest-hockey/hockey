def test_stale_revision_fails_freshness_even_when_pair_matches(tmp_path):
    export_dir, _, _ = _export_pair(tmp_path, revision=REVISION)

    report = verify_export_parity(export_dir, required_canonical_revision=OTHER_REVISION)

    assert report["status"] == STATUS_FAIL
    assert any(reason["code"] == "stale_canonical_revision" for reason in report["reasons"])


def test_artifact_revision_mismatch_fails(tmp_path):
    export_dir, xlsx, _ = _export_pair(tmp_path, revision=REVISION)
    # Re-export only the workbook with a different embedded revision.
    workbook = openpyxl.load_workbook(xlsx)
    sheet = workbook["Eksportmetadata"]
    for row in sheet.iter_rows():
        if row[0].value == "Kanonisk revisjon":
            row[1].value = OTHER_REVISION
    workbook.save(xlsx)

    report = verify_export_parity(export_dir)

    assert report["status"] == STATUS_FAIL
    assert any(reason["code"] == "artifact_revision_mismatch" for reason in report["reasons"])


def test_publish_gate_passes_clean_pair_and_blocks_mismatch(tmp_path):
    export_dir, xlsx, _ = _export_pair(tmp_path)
    assert publish_parity_gate(export_dir=export_dir, repo_dir=tmp_path) is None

    workbook = openpyxl.load_workbook(xlsx)
    sheet = workbook["Sesongoversikt"]
    header = [cell.value for cell in sheet[1]]
    arena_col = header.index("Arena") + 1
    sheet.cell(row=2, column=arena_col).value = "Feil arena"
    workbook.save(xlsx)

    blocked = publish_parity_gate(export_dir=export_dir, repo_dir=tmp_path)
    assert blocked is not None
    assert blocked.status == "failed"
    assert any(
        evidence.startswith("export_parity_mismatch=") and "arena" in evidence
        for evidence in blocked.evidence
        if isinstance(evidence, str)
    )


